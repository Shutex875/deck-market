export const calculateAverageElixir = (cards: unknown): number => {
  if (!Array.isArray(cards) || cards.length !== 8 || !cards.every(card => typeof card === 'string')) {
    throw new Error('Exactly 8 card IDs are required to calculate average elixir');
  }

  const unknownCards = cards.filter(card => ELIXIR_COST_BY_CARD[card] === undefined);
  if (unknownCards.length > 0) {
    throw new Error(`Elixir cost is not configured for: ${unknownCards.join(', ')}`);
  }

  const totalCost = cards.reduce<number>((sum, card) => sum + ELIXIR_COST_BY_CARD[card], 0);
  return Math.round((totalCost / 8) * 10) / 10;
};
